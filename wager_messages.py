WAGER_KINDS = ("announce", "win", "lose", "tease", "none")


def pick_wager_line(god: str, kind: str, config=None) -> str:
    """取一句赌局文案。

    优先级：配置里的按神明池 → 配置里的按类型池 → 内置神明池 → 内置通用池。
    配置池为空列表/空字典时视为"没配"，与其它文案池的约定一致。
    """
    from astrbot_plugin_faith_ladder.plugin_config import cfg_get

    if kind not in WAGER_KINDS:
        return ""

    for key in (f"wager_messages_{kind}_{god}", f"wager_messages_{kind}"):
        pool = cfg_get(config or {}, key) or []
        if pool:
            return random.choice(pool)

    builtin = WAGER_MESSAGES.get(god, {}).get(kind) or GENERIC_WAGER_MESSAGES.get(kind) or []
    return random.choice(builtin) if builtin else ""
